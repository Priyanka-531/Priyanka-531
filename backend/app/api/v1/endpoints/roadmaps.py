import uuid
from datetime import datetime, timezone
from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from app.core.database import get_db
from app.core.dependencies import get_current_user
from app.models.user import User
from app.models.roadmap import Roadmap, RoadmapTask
from app.schemas.roadmap import (
    RoadmapGenerateRequest,
    RoadmapResponse,
    RoadmapTaskResponse,
    RoadmapTaskUpdateRequest
)
from app.services.roadmap_service import build_roadmap_plan

router = APIRouter(prefix="/roadmaps", tags=["Roadmaps"])

@router.post("/generate", response_model=RoadmapResponse, status_code=status.HTTP_201_CREATED)
def generate_roadmap(
    payload: RoadmapGenerateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Generate a personalized weekly learning roadmap for the student.
    Persists roadmap and individual actionable daily tasks in PostgreSQL.
    """
    target_role = payload.target_role or "Software Developer"
    total_weeks = payload.total_weeks or 4
    daily_hours = payload.daily_hours or 2
    missing_skills = payload.missing_skills or []

    # 1. Generate task plan
    task_plans = build_roadmap_plan(
        target_role=target_role,
        missing_skills=missing_skills,
        daily_hours=daily_hours,
        total_weeks=total_weeks
    )

    # 2. Create Roadmap container
    roadmap = Roadmap(
        user_id=current_user.id,
        target_role=target_role,
        title=f"{target_role} Skill Accelerator Roadmap",
        summary=f"{total_weeks}-week curriculum tailored for {daily_hours} hrs/day, bridging critical skills.",
        total_weeks=total_weeks,
        daily_hours=daily_hours
    )
    db.add(roadmap)
    db.flush()

    # 3. Create all tasks
    for item in task_plans:
        task = RoadmapTask(
            roadmap_id=roadmap.id,
            week_number=item["week_number"],
            day_number=item["day_number"],
            title=item["title"],
            explanation=item["explanation"],
            skill_category=item["skill_category"],
            estimated_duration_minutes=item["estimated_duration_minutes"],
            resource_name=item.get("resource_name"),
            resource_url=item.get("resource_url"),
            is_completed=False
        )
        db.add(task)

    db.commit()
    db.refresh(roadmap)
    return roadmap


@router.get("", response_model=List[RoadmapResponse])
def get_user_roadmaps(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    List all roadmaps generated by the user.
    """
    return db.query(Roadmap).filter(Roadmap.user_id == current_user.id).order_by(Roadmap.created_at.desc()).all()


@router.get("/active", response_model=Optional[RoadmapResponse])
def get_active_roadmap(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Get the most recently created roadmap for the user.
    """
    roadmap = db.query(Roadmap).filter(Roadmap.user_id == current_user.id).order_by(Roadmap.created_at.desc()).first()
    if not roadmap:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No active roadmap found."
        )
    return roadmap


@router.get("/{roadmap_id}", response_model=RoadmapResponse)
def get_roadmap_by_id(
    roadmap_id: uuid.UUID,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Get roadmap by ID with all tasks, verifying user ownership.
    """
    roadmap = db.query(Roadmap).filter(Roadmap.id == roadmap_id, Roadmap.user_id == current_user.id).first()
    if not roadmap:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Roadmap not found or access denied."
        )
    return roadmap


@router.patch("/tasks/{task_id}", response_model=RoadmapTaskResponse)
def update_task_completion(
    task_id: uuid.UUID,
    payload: RoadmapTaskUpdateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """
    Toggle task completion status (is_completed: True/False).
    Verifies user ownership via parent roadmap.
    """
    task = db.query(RoadmapTask).join(Roadmap).filter(
        RoadmapTask.id == task_id,
        Roadmap.user_id == current_user.id
    ).first()

    if not task:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Roadmap task not found or access denied."
        )

    task.is_completed = payload.is_completed
    task.completed_at = datetime.now(timezone.utc) if payload.is_completed else None

    db.commit()
    db.refresh(task)
    return task
